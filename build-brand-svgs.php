<?php
// One-time builder: fetches brand SVGs and writes includes/brand_svgs.php
// Run: php build-brand-svgs.php   (from the app root)
$icons = ['claude', 'openai', 'googlegemini', 'perplexity'];
$out = "<?php\n// Generated by build-brand-svgs.php - inline brand SVGs (simple-icons)\nreturn [\n";
foreach ($icons as $n) {
    $svg = file_get_contents('https://cdn.jsdelivr.net/npm/simple-icons@13/icons/' . $n . '.svg');
    if ($svg === false || strpos($svg, '<svg') !== 0) {
        fwrite(STDERR, "FAILED: $n\n");
        exit(1);
    }
    $svg = str_replace('<svg ', '<svg width="16" height="16" ', $svg);
    $out .= '    ' . var_export($n, true) . ' => ' . var_export($svg, true) . ",\n";
    fwrite(STDERR, "OK: $n (" . strlen($svg) . " bytes)\n");
}
$out .= "];\n";
if (!is_dir(__DIR__ . '/includes')) {
    mkdir(__DIR__ . '/includes');
}
file_put_contents(__DIR__ . '/includes/brand_svgs.php', $out);
fwrite(STDERR, "Written: includes/brand_svgs.php\n");
